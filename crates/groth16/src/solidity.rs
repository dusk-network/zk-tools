fn solidity_integer_type(name: &str, prefix: &str) -> bool {
    name.strip_prefix(prefix)
        .and_then(|width| width.parse::<u16>().ok())
        .is_some_and(|width| (8..=256).contains(&width) && width % 8 == 0)
}

fn solidity_fixed_type(name: &str, prefix: &str) -> bool {
    name.strip_prefix(prefix)
        .and_then(|dimensions| dimensions.split_once('x'))
        .and_then(|(width, decimals)| {
            Some((width.parse::<u16>().ok()?, decimals.parse::<u8>().ok()?))
        })
        .is_some_and(|(width, decimals)| {
            (8..=256).contains(&width) && width % 8 == 0 && decimals <= 80
        })
}

fn encode_g1(point: &G1Affine) -> [u8; EIP2537_G1_SIZE] {
    if bool::from(point.is_identity()) {
        return [0u8; EIP2537_G1_SIZE];
    }

    let uncompressed = point.to_uncompressed();
    let mut encoded = [0u8; EIP2537_G1_SIZE];
    encoded[16..64].copy_from_slice(&uncompressed[..48]);
    encoded[80..128].copy_from_slice(&uncompressed[48..]);
    encoded
}

fn encode_g2(point: &G2Affine) -> [u8; EIP2537_G2_SIZE] {
    if bool::from(point.is_identity()) {
        return [0u8; EIP2537_G2_SIZE];
    }

    // dusk-curves follows the IETF serialization order c1 || c0, whereas
    // EIP-2537 requires c0 || c1 for every Fp2 element.
    let uncompressed = point.to_uncompressed();
    let mut encoded = [0u8; EIP2537_G2_SIZE];
    encoded[16..64].copy_from_slice(&uncompressed[48..96]);
    encoded[80..128].copy_from_slice(&uncompressed[..48]);
    encoded[144..192].copy_from_slice(&uncompressed[144..192]);
    encoded[208..256].copy_from_slice(&uncompressed[96..144]);
    encoded
}

fn write_store_g1(
    source: &mut String,
    base: &str,
    offset: usize,
    point: &G1Affine,
) -> Result<(), SolidityError> {
    let encoded = encode_g1(point);
    writeln!(
        source,
        "            storeG1(\n                add({base}, 0x{offset:x}),\n                0x{},\n                0x{},\n                0x{},\n                0x{}\n            )",
        HexWord(&encoded[0..32]),
        HexWord(&encoded[32..64]),
        HexWord(&encoded[64..96]),
        HexWord(&encoded[96..128]),
    )
    .map_err(|_| SolidityError::Formatting)
}

fn write_store_g2(
    source: &mut String,
    base: &str,
    offset: usize,
    point: &G2Affine,
) -> Result<(), SolidityError> {
    let encoded = encode_g2(point);
    write!(
        source,
        "            storeG2(\n                add({base}, 0x{offset:x})"
    )
    .map_err(|_| SolidityError::Formatting)?;
    for word in encoded.chunks_exact(32) {
        write!(source, ",\n                0x{}", HexWord(word))
            .map_err(|_| SolidityError::Formatting)?;
    }
    source.push_str("\n            )\n");
    Ok(())
}

struct HexWord<'a>(&'a [u8]);

impl fmt::Display for HexWord<'_> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        for byte in self.0 {
            write!(formatter, "{byte:02x}")?;
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use dusk_curves::bls12_381::BlsScalar;

    fn decode_hex<const N: usize>(value: &str) -> [u8; N] {
        assert_eq!(value.len(), N * 2);
        let mut output = [0u8; N];
        for (index, byte) in output.iter_mut().enumerate() {
            *byte = u8::from_str_radix(&value[index * 2..index * 2 + 2], 16).unwrap();
        }
        output
    }

    #[test]
    fn eip2537_generator_encodings_match_the_specification() {
        let g1 = encode_g1(&G1Affine::generator());
        assert_eq!(&g1[..16], &[0u8; 16]);
        assert_eq!(
            &g1[16..64],
            &decode_hex::<48>(
                "17f1d3a73197d7942695638c4fa9ac0fc3688c4f9774b905a14e3a3f171bac586c55e83ff97a1aeffb3af00adb22c6bb"
            )
        );
        assert_eq!(
            &g1[80..128],
            &decode_hex::<48>(
                "08b3f481e3aaa0f1a09e30ed741d8ae4fcf5e095d5d00af600db18cb2c04b3edd03cc744a2888ae40caa232946c5e7e1"
            )
        );

        let g2 = encode_g2(&G2Affine::generator());
        for offset in [0, 64, 128, 192] {
            assert_eq!(&g2[offset..offset + 16], &[0u8; 16]);
        }
        for (offset, expected) in [
            (
                16,
                "024aa2b2f08f0a91260805272dc51051c6e47ad4fa403b02b4510b647ae3d1770bac0326a805bbefd48056c8c121bdb8",
            ),
            (
                80,
                "13e02b6052719f607dacd3a088274f65596bd0d09920b61ab5da61bbdc7f5049334cf11213945d57e5ac7d055d042b7e",
            ),
            (
                144,
                "0ce5d527727d6e118cc9cdc6da2e351aadfd9baa8cbdd3a76d429a695160d12c923ac9cc3baca289e193548608b82801",
            ),
            (
                208,
                "0606c4a02ea734cc32acd2b02bc28b99cb3e287e85a763af267492ab572e99ab3f370d275cec1da1aaa9075ff05f79be",
            ),
        ] {
            assert_eq!(&g2[offset..offset + 48], &decode_hex::<48>(expected));
        }
    }

    #[test]
    fn proof_transport_is_neg_a_b_c() {
        let proof = Proof {
            a: G1Affine::generator(),
            b: G2Affine::generator(),
            c: G1Affine::from(G1Affine::generator() * BlsScalar::from(2u64)),
        };
        let encoded = proof.to_eip2537().into_bytes();
        assert_eq!(&encoded[..128], &encode_g1(&(-proof.a)));
        assert_eq!(&encoded[128..384], &encode_g2(&proof.b));
        assert_eq!(&encoded[384..], &encode_g1(&proof.c));
    }

    #[test]
    fn scalar_transport_is_big_endian() {
        let encoded = encode_eip2537_scalar(&BlsScalar::from(0x0102u64));
        assert_eq!(&encoded[..30], &[0u8; 30]);
        assert_eq!(&encoded[30..], &[1, 2]);
    }

    #[test]
    fn generated_verifier_is_key_specific_and_names_are_checked() {
        let key = VerifyingKey {
            alpha_g1: G1Affine::generator(),
            beta_g2: G2Affine::generator(),
            gamma_g2: G2Affine::generator(),
            delta_g2: G2Affine::generator(),
            public_query: alloc::vec![G1Affine::generator(), G1Affine::generator()],
        };
        let source = key.solidity_verifier("SquareVerifier").unwrap();
        assert!(source.contains("contract SquareVerifier"));
        assert!(source.contains("PUBLIC_INPUTS = 1"));
        assert!(source.contains("staticcall(24000, 0x0c"));
        assert!(source.contains("staticcall(168100, 0x0f"));
        assert_eq!(
            key.solidity_verifier("not-valid"),
            Err(SolidityError::InvalidContractName)
        );
        for invalid in ["", "1Verifier", "contract", "uint256", "bytes32"] {
            assert_eq!(
                key.solidity_verifier(invalid),
                Err(SolidityError::InvalidContractName)
            );
        }
    }

    #[test]
    fn generated_verifier_supports_different_public_input_counts() {
        let key = |public_inputs: usize| VerifyingKey {
            alpha_g1: G1Affine::generator(),
            beta_g2: G2Affine::generator(),
            gamma_g2: G2Affine::generator(),
            delta_g2: G2Affine::generator(),
            public_query: alloc::vec![G1Affine::generator(); public_inputs + 1],
        };

        let no_inputs = key(0).solidity_verifier("NoInputVerifier").unwrap();
        assert!(no_inputs.contains("PUBLIC_INPUTS = 0"));
        assert!(no_inputs.contains("msmInput, 0xa0, vkX"));
        assert!(!no_inputs.contains("publicInputs.offset"));

        let two_inputs = key(2).solidity_verifier("TwoInputVerifier").unwrap();
        assert!(two_inputs.contains("PUBLIC_INPUTS = 2"));
        assert!(two_inputs.contains("msmInput, 0x1e0, vkX"));
        assert!(two_inputs.contains("publicInputs.offset, 0x0"));
        assert!(two_inputs.contains("publicInputs.offset, 0x20"));
    }
}
